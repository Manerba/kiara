"""Stable global IDs for generated evidence files and unfulfilled output slots.

Version 1 uses SHA256 of UTF-8 encoded compact JSON, ensure_ascii=True,
separators=(',', ':'), no newline or BOM. The exact arrays are:
  [1, 'artifact', experiment_id, case_id, role, sha256]
  [1, 'slot', experiment_id, case_id, role]

All IDs/roles use the shared case-sensitive ID grammar; sha256 is lowercase.
An artifact identity includes the file's content hash. A slot is a plan, never
an assertion that output exists or was measured. No file I/O or evaluation.
"""
import hashlib
import json
import re

ID_PATTERN = r"[A-Za-z][A-Za-z0-9_.-]{0,119}"
_ID = re.compile(ID_PATTERN)
_SHA = re.compile(r"[a-f0-9]{64}")


def _validate_ids(values):
    for value in values:
        if type(value) is not str or not _ID.fullmatch(value):
            raise ValueError("invalid_id")


def _digest(values):
    data = json.dumps(values, ensure_ascii=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def artefakt_id(experiment_id, case_id, role, sha256):
    """Global generated byte identity; authoritative inputs keep their own IDs."""
    _validate_ids((experiment_id, case_id, role))
    if type(sha256) is not str or not _SHA.fullmatch(sha256):
        raise ValueError("invalid_sha256")
    return "artifact." + _digest([1, "artifact", experiment_id, case_id, role, sha256])


def slot_id(experiment_id, case_id, role):
    """Stable planned output slot without an artifact/content assertion."""
    _validate_ids((experiment_id, case_id, role))
    return "slot." + _digest([1, "slot", experiment_id, case_id, role])
