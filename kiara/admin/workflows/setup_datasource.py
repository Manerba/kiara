from kiara.admin.workflows.base import WorkflowDefinition, WorkflowStep

SETUP_DATASOURCE = WorkflowDefinition(
    name="setup.datasource",
    label="Datenquelle einrichten",
    description="Neue Datenquelle testweise pruefen und anlegen.",
    category="setup",
    help_text=(
        "Fuehrt durch Konnektorwahl, Verbindungstest und Anlage einer "
        "Datenquelle. `datasource.browse` ist bewusst nicht Teil dieses "
        "Guided Setups."
    ),
    steps=[
        WorkflowStep(
            id="show_connector_types",
            label="Konnektor-Typen anzeigen",
            description="Lade zuerst die verfuegbaren Konnektor-Typen ueber `datasource.connector_types`.",
            action="datasource.connector_types",
            next_step_ids=["collect_datasource_identity"],
        ),
        WorkflowStep(
            id="collect_datasource_identity",
            label="Datenquelle beschreiben",
            description="Sammle Anzeigename, Konnektor-Typ und die rohe Konnektor-Konfiguration als `config`.",
            required_inputs=["name", "type", "config"],
            optional_inputs=[
                "ds_chunk_strategy",
                "ds_chunk_size",
                "ds_chunk_overlap",
                "ds_file_types",
                "ds_exclude_patterns",
                "ds_ddu_enabled",
                "ds_ddu_ocr_images",
                "ds_vlm_enabled",
                "ds_accept_all_text",
                "ds_index_attachments",
                "sync_interval",
                "restriction_level",
                "ds_contextual_retrieval",
                "ds_enrichment_prompt_id",
                "ds_enrichment_backend_id",
                "ds_colbert_enabled",
            ],
            next_step_ids=["test_connection"],
        ),
        WorkflowStep(
            id="test_connection",
            label="Verbindung testen",
            description="Rufe `datasource.test_connection` mit `type=type` und `config=config` auf.",
            action="datasource.test_connection",
            required_inputs=["type", "config"],
            param_mapping={"type": "type", "config": "config"},
            next_step_ids=["create_datasource"],
        ),
        WorkflowStep(
            id="create_datasource",
            label="Datenquelle anlegen",
            description=(
                "Rufe `datasource.create` auf, mappe `config` auf "
                "`connector_config` und reiche optionale Ingestion-Felder nur "
                "weiter, wenn der Admin sie explizit angegeben hat."
            ),
            action="datasource.create",
            required_inputs=["name", "type", "config"],
            optional_inputs=[
                "ds_chunk_strategy",
                "ds_chunk_size",
                "ds_chunk_overlap",
                "ds_file_types",
                "ds_exclude_patterns",
                "ds_ddu_enabled",
                "ds_ddu_ocr_images",
                "ds_vlm_enabled",
                "ds_accept_all_text",
                "ds_index_attachments",
                "sync_interval",
                "restriction_level",
                "ds_contextual_retrieval",
                "ds_enrichment_prompt_id",
                "ds_enrichment_backend_id",
                "ds_colbert_enabled",
            ],
            param_mapping={
                "name": "name",
                "type": "type",
                "connector_config": "config",
                "ds_chunk_strategy": "ds_chunk_strategy",
                "ds_chunk_size": "ds_chunk_size",
                "ds_chunk_overlap": "ds_chunk_overlap",
                "ds_file_types": "ds_file_types",
                "ds_exclude_patterns": "ds_exclude_patterns",
                "ds_ddu_enabled": "ds_ddu_enabled",
                "ds_ddu_ocr_images": "ds_ddu_ocr_images",
                "ds_vlm_enabled": "ds_vlm_enabled",
                "ds_accept_all_text": "ds_accept_all_text",
                "ds_index_attachments": "ds_index_attachments",
                "sync_interval": "sync_interval",
                "restriction_level": "restriction_level",
                "ds_contextual_retrieval": "ds_contextual_retrieval",
                "ds_enrichment_prompt_id": "ds_enrichment_prompt_id",
                "ds_enrichment_backend_id": "ds_enrichment_backend_id",
                "ds_colbert_enabled": "ds_colbert_enabled",
            },
            output_keys=["ds_id"],
            next_step_ids=["done"],
        ),
        WorkflowStep(
            id="done",
            label="Abgeschlossen",
            description="Die Datenquelle ist angelegt und steht fuer weitere Schritte bereit.",
        ),
    ],
    required_functions=[
        "datasource.connector_types",
        "datasource.test_connection",
        "datasource.create",
        "datasource.list",
    ],
    resume_checks=["datasource.list"],
    can_auto_execute=False,
)
