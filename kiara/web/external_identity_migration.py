"""Idempotente Migration fuer externe User-Identitaeten."""

from __future__ import annotations

_MIGRATION_LOCK_KEY = 681034


def migrate_external_identity_schema(conn=None) -> None:
    """Legt ``user_external_identities`` nicht-destruktiv an bzw. aktualisiert sie."""
    close_conn = False
    if conn is None:
        from kiara.shared.db import get_db

        conn = get_db()
        close_conn = True

    try:
        if not _has_users_table(conn):
            return
        conn.execute("SELECT pg_advisory_xact_lock(%s)", (_MIGRATION_LOCK_KEY,))
        _create_or_update_table(conn)
        _create_updated_at_trigger(conn)
        if close_conn:
            conn.commit()
    except Exception:
        if close_conn:
            conn.rollback()
        raise
    finally:
        if close_conn:
            conn.close()


def _has_users_table(conn) -> bool:
    row = conn.execute(
        "SELECT 1 FROM information_schema.tables "
        "WHERE table_schema = 'public' AND table_name = 'users' LIMIT 1"
    ).fetchone()
    return row is not None


def _create_or_update_table(conn) -> None:
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS public.user_external_identities (
            id integer GENERATED BY DEFAULT AS IDENTITY,
            provider text NOT NULL,
            issuer text NOT NULL,
            identity_claim text NOT NULL,
            external_id text NOT NULL,
            user_id integer NOT NULL,
            is_active boolean DEFAULT true NOT NULL,
            created_at timestamp with time zone DEFAULT now() NOT NULL,
            updated_at timestamp with time zone DEFAULT now() NOT NULL
        )
        """
    )
    conn.execute(
        """
        ALTER TABLE public.user_external_identities
            ADD COLUMN IF NOT EXISTS id integer GENERATED BY DEFAULT AS IDENTITY,
            ADD COLUMN IF NOT EXISTS provider text,
            ADD COLUMN IF NOT EXISTS issuer text,
            ADD COLUMN IF NOT EXISTS identity_claim text,
            ADD COLUMN IF NOT EXISTS external_id text,
            ADD COLUMN IF NOT EXISTS user_id integer,
            ADD COLUMN IF NOT EXISTS is_active boolean DEFAULT true,
            ADD COLUMN IF NOT EXISTS created_at timestamp with time zone DEFAULT now(),
            ADD COLUMN IF NOT EXISTS updated_at timestamp with time zone DEFAULT now()
        """
    )
    for column in [
        "provider",
        "issuer",
        "identity_claim",
        "external_id",
        "user_id",
        "is_active",
        "created_at",
        "updated_at",
    ]:
        conn.execute(
            f"ALTER TABLE public.user_external_identities ALTER COLUMN {column} SET NOT NULL"
        )
    conn.execute(
        "ALTER TABLE public.user_external_identities ALTER COLUMN is_active SET DEFAULT true"
    )
    conn.execute(
        "ALTER TABLE public.user_external_identities ALTER COLUMN created_at SET DEFAULT now()"
    )
    conn.execute(
        "ALTER TABLE public.user_external_identities ALTER COLUMN updated_at SET DEFAULT now()"
    )

    conn.execute(
        """
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'user_external_identities_pkey'
            ) THEN
                ALTER TABLE public.user_external_identities
                    ADD CONSTRAINT user_external_identities_pkey PRIMARY KEY (id);
            END IF;
        END $$;
        """
    )
    conn.execute(
        """
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'user_external_identities_unique_external'
            ) THEN
                ALTER TABLE public.user_external_identities
                    ADD CONSTRAINT user_external_identities_unique_external
                    UNIQUE (provider, issuer, identity_claim, external_id);
            END IF;
        END $$;
        """
    )
    conn.execute(
        """
        DO $$
        BEGIN
            IF NOT EXISTS (
                SELECT 1 FROM pg_constraint
                WHERE conname = 'user_external_identities_user_id_fkey'
            ) THEN
                ALTER TABLE public.user_external_identities
                    ADD CONSTRAINT user_external_identities_user_id_fkey
                    FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
            END IF;
        END $$;
        """
    )
    for constraint, expression in [
        ("user_external_identities_provider_nonempty", "btrim(provider) <> ''"),
        ("user_external_identities_issuer_nonempty", "btrim(issuer) <> ''"),
        ("user_external_identities_claim_nonempty", "btrim(identity_claim) <> ''"),
        ("user_external_identities_external_nonempty", "btrim(external_id) <> ''"),
        (
            "user_external_identities_ad_sid_format",
            "external_id ~ '^S-1-[0-9]+(-[0-9]+)+$'",
        ),
    ]:
        conn.execute(
            f"""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint WHERE conname = '{constraint}'
                ) THEN
                    ALTER TABLE public.user_external_identities
                        ADD CONSTRAINT {constraint} CHECK ({expression});
                END IF;
            END $$;
            """
        )

    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_user_external_identities_user "
        "ON public.user_external_identities USING btree (user_id)"
    )
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_user_external_identities_active_user "
        "ON public.user_external_identities "
        "(provider, issuer, identity_claim, user_id) WHERE is_active"
    )


def _create_updated_at_trigger(conn) -> None:
    conn.execute(
        """
        CREATE OR REPLACE FUNCTION public.set_user_external_identities_updated_at()
        RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            NEW.updated_at = now();
            RETURN NEW;
        END;
        $$;
        """
    )
    conn.execute(
        """
        DROP TRIGGER IF EXISTS trg_user_external_identities_updated_at
        ON public.user_external_identities
        """
    )
    conn.execute(
        """
        CREATE TRIGGER trg_user_external_identities_updated_at
        BEFORE UPDATE ON public.user_external_identities
        FOR EACH ROW
        EXECUTE FUNCTION public.set_user_external_identities_updated_at()
        """
    )
